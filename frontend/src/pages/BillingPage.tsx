import * as React from 'react';
import { Link } from 'react-router-dom';
import { toast } from 'sonner';
import { Button } from '@/components/ui/button';
import { Chips, InlineError, Toolbar, ToolbarSpacer } from '@/components/ds/kit';
import { Icon } from '@/components/ds/Icon';
import { PageHeader } from '@/components/ds/primitives';
import { SystemLogo } from '@/components/ds/SystemLogo';
import { BackbonePanel } from '@/components/sim/BackbonePanel';
import { SIMULATORS, simByService } from '@/config/simulators';
import { errorText, num } from '@/core/format';
import { getBillingOverview, seedBillingTelco, type BillingOverview } from '@/services/api';

type Layer = 'all' | 'BSS' | 'OSS' | 'NSS';

const TELECOM = ['bss', 'nss', 'oss'] as const;
const LAYER_SERVICE: Record<Exclude<Layer, 'all'>, string> = { BSS: 'bss', OSS: 'oss', NSS: 'nss' };

/** Live billing data from BSS, OSS, and NSS simulators (same drill-down as each system page). */
export default function BillingPage() {
  const [data, setData] = React.useState<BillingOverview | null>(null);
  const [loading, setLoading] = React.useState(true);
  const [error, setError] = React.useState<string | null>(null);
  const [layer, setLayer] = React.useState<Layer>('all');
  const [seeding, setSeeding] = React.useState(false);
  const [attempt, setAttempt] = React.useState(0);
  const [refreshKey, setRefreshKey] = React.useState(0);

  React.useEffect(() => {
    let alive = true;
    setLoading(true);
    setError(null);
    getBillingOverview(layer === 'all' ? undefined : layer)
      .then(d => { if (alive) setData(d); })
      .catch(e => { if (alive) setError(errorText(e)); })
      .finally(() => { if (alive) setLoading(false); });
    return () => { alive = false; };
  }, [layer, attempt, refreshKey]);

  const totals = data?.totals;
  const byLayer = totals?.by_layer;

  const seedBilling = async () => {
    setSeeding(true);
    try {
      await seedBillingTelco();
      toast.success('BSS, NSS, and OSS re-seeded with billing data.');
      setAttempt(a => a + 1);
      setRefreshKey(k => k + 1);
    } catch (e) {
      toast.error(errorText(e));
    } finally {
      setSeeding(false);
    }
  };

  const visibleServices = layer === 'all'
    ? [...TELECOM]
    : [LAYER_SERVICE[layer]];

  return (
    <div className="page space-y-6">
      <PageHeader
        title="Billing"
        description="Billing-related tables, files, APIs, and streams generated by the BSS, OSS, and NSS simulators — open rows and artifacts the same way as on each system page."
        actions={
          <div className="flex flex-wrap items-center gap-2">
            <Button variant="outline" size="sm" onClick={() => { setAttempt(a => a + 1); setRefreshKey(k => k + 1); }} disabled={loading}>
              <Icon name="refresh" className={loading ? 'animate-spin' : ''} /> Refresh
            </Button>
            <Button size="sm" onClick={seedBilling} disabled={seeding}>
              <Icon name={seeding ? 'spinner' : 'sparkles'} className={seeding ? 'animate-spin' : ''} />
              Seed billing data
            </Button>
            <a
              href="/telco-atlas/kenan.html"
              target="_blank"
              rel="noreferrer"
              className="text-sm text-primary underline-offset-4 hover:underline dark:text-brand-hi"
            >
              Feed reference
            </a>
          </div>
        }
      />

      {error && <InlineError onRetry={() => setAttempt(a => a + 1)}>{error}</InlineError>}

      <Toolbar className="flex-wrap gap-3">
        <Chips<Layer>
          label="Layer"
          value={layer}
          onChange={setLayer}
          options={[
            { value: 'all', label: 'All layers', count: totals?.tables },
            { value: 'BSS', label: 'BSS', count: byLayer?.tables?.BSS },
            { value: 'OSS', label: 'OSS', count: byLayer?.tables?.OSS },
            { value: 'NSS', label: 'NSS', count: byLayer?.tables?.NSS },
          ]}
        />
        <ToolbarSpacer />
        {totals && (
          <span className="num text-xs text-muted-foreground" aria-live="polite">
            {loading ? 'Updating…' : `${num(totals.tables)} billing tables · ${num(totals.rows)} rows`}
          </span>
        )}
      </Toolbar>

      {!loading && totals && totals.tables === 0 && (
        <p className="rounded-lg border border-border bg-surface-2/50 px-4 py-3 text-sm text-muted-foreground">
          No billing-tagged data yet. Choose <strong>Seed billing data</strong>, or open{' '}
          {TELECOM.map((s, i) => {
            const sim = simByService(s);
            return (
              <React.Fragment key={s}>
                {i > 0 && (i === TELECOM.length - 1 ? ' or ' : ', ')}
                <Link to={`/simulators/${sim?.id}`} className="text-primary underline-offset-4 hover:underline dark:text-brand-hi">
                  {sim?.short}
                </Link>
              </React.Fragment>
            );
          })}{' '}
          and generate billing families from the backbone.
        </p>
      )}

      <div className="space-y-10">
        {visibleServices.map(svc => {
          const sim = SIMULATORS.find(x => x.service === svc);
          if (!sim) return null;
          const bundle = data?.layers?.[svc];
          const t = bundle?.totals;
          return (
            <section key={svc} className="space-y-4" aria-label={`${sim.short} billing`}>
              <TrackingHeader
                sim={sim}
                rows={t?.rows}
                tables={t?.tables}
                files={t?.files}
                apis={t?.apis}
                streams={t?.streams}
              />
              <BackbonePanel key={`${svc}-${refreshKey}`} sim={sim} billingOnly />
            </section>
          );
        })}
      </div>
    </div>
  );
}

function TrackingHeader({
  sim,
  rows,
  tables,
  files,
  apis,
  streams,
}: {
  sim: (typeof SIMULATORS)[number];
  rows?: number;
  tables?: number;
  files?: number;
  apis?: number;
  streams?: number;
}) {
  return (
    <a href={`/simulators/${sim.id}`} className="group flex flex-wrap items-center gap-3 border-b border-border pb-3">
      <SystemLogo system={sim.logo} size="md" />
      <div className="min-w-0 flex-1">
        <h2 className="text-md font-medium text-foreground group-hover:text-primary dark:group-hover:text-brand-hi">
          {sim.name}
        </h2>
        <p className="text-xs text-muted-foreground">
          {num(tables ?? 0)} tables · {num(rows ?? 0)} rows · {num(files ?? 0)} files · {num(apis ?? 0)} APIs · {num(streams ?? 0)} streams
        </p>
      </div>
      <span className="text-xs text-muted-foreground">Open full system →</span>
    </a>
  );
}